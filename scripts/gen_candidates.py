"""Generate the 16 candidate models into models/candidates/.

Each candidate has the shape of models/baselines/tso.cat; only the ppo line changes.
One yes/no flag per program-order pair: is W->W, W->R, R->R, R->W preserved?
"""
import itertools
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAIRS = ["WW", "WR", "RR", "RW"]  # flag order in the file name

TEMPLATE = """\
"{name}"
include "cos.cat"

(* Generated by scripts/gen_candidates.py, do not edit by hand *)
let com = rf | co | fr
acyclic po-loc | com as uniproc

(* Preserved program-order pairs: {kept} *)
let ppo = {ppo}
(* rfe, not rf: when W->R is preserved, rfi is already inside ppo *)
acyclic ppo | rfe | co | fr as global
"""


def main():
    for flags in itertools.product([0, 1], repeat=len(PAIRS)):
        name = "cand_" + "_".join(f"{pair}{flag}" for pair, flag in zip(PAIRS, flags))
        kept = [pair for pair, flag in zip(PAIRS, flags) if flag]
        # "WR" becomes (po & (W * R)); 0 is cat's empty relation, used when nothing is kept
        ppo = " | ".join(f"(po & ({pair[0]} * {pair[1]}))" for pair in kept) or "0"
        kept_text = ", ".join(f"{pair[0]}->{pair[1]}" for pair in kept) or "none"
        path = ROOT / "models" / "candidates" / f"{name}.cat"
        path.write_text(TEMPLATE.format(name=name, kept=kept_text, ppo=ppo))
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
